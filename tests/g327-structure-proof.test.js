import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const evidence=path.join(ROOT,'docs/evidence/g3');
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
test('G3.27 immutable source SHA links to G3.26 and known old server/worker bytes',async()=>{
 const report=JSON.parse(await fs.readFile(path.join(evidence,'g3-27-image-structure-preflight-contract.json'),'utf8'));
 const parent=await fs.readFile(path.join(evidence,'g3-26-harmless-image-boundary.json'));
 assert.equal(report.previousG326PublicProofSha256,sha(parent));
 assert.equal(report.trackedReadOnlyPreviousServerSha256,sha(await fs.readFile(path.join(ROOT,'server/index.js'))));
 assert.equal(report.trackedReadOnlyPreviousPythonWorkerSha256,sha(await fs.readFile(path.join(ROOT,'engines/triposr/worker.py'))));
 assert.equal(report.boundedPreflightSourceSha256,sha(await fs.readFile(path.join(ROOT,'server/image-structure-preflight.js'))));
 assert.equal(report.sourceFixturesSha256,sha(await fs.readFile(path.join(ROOT,'tests/fixtures/g327-synthetic-images.json'))));
 assert.deepEqual(report.validatedFormats,['PNG','JPEG','WEBP']);
 assert.equal(report.fixtureResults.length,3);
 assert.equal(report.fixtureResults.reduce((s,x)=>s+x.syntheticallyTruncatedVariantsRejected,0),18);
 assert.equal(report.proposedStrictPreflightIntegratedIntoProduction,false);
 assert.equal(report.legacyG1ShortSignatureOnlyStillInProduction,true);
 assert.equal(report.completeImageDecodeOrSecurityProven,false);
 assert.equal(report.securityIssue4Resolved,false);
 assert.equal(report.newUntrustedImageUploadsApproved,false);
 assert.equal(report.printQualified,false);
 assert.equal(report.fabricationAction,'NONE');
});
test('G3.27 synthetic-only public proof never includes customer paths or GPU/print clearance',async()=>{
 const raw=await fs.readFile(path.join(evidence,'g3-27-image-structure-preflight-contract.json'),'utf8');
 assert.doesNotMatch(raw,/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i);
 assert.doesNotMatch(raw,/D:[/\\]|customerEmail|jobId|sourceImagePath|modelWeightsPath|apiToken/i);
 const result=JSON.parse(raw);
 assert.equal(result.customerMediaProcessed,false);
 assert.equal(result.OSNativeParserSandboxReady,false);
 assert.equal(result.liveG2DependenciesChanged,false);
 assert.equal(result.additionalModelExecutions,0);
 assert.equal(result.GPUInferenceRuns,0);
 assert.equal(result.packagesInstalled,0);
 assert.equal(result.approvedForPrinter,false);
});
